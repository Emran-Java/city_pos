package acquire.sdk.device.constant;

/**
 * Sub Screen Type
 *
 * @author Janson
 * @since 2025/9/28
 */
public class SubScreenType {
    /**
     * No exist any sub screen
     */
    public final static int NONE = 0xFF;
    /**
     * Has a clickable sub screen
     */
    public final static int CLICKABLE = 0x01;
    /**
     * Has a sub screen but unclickable
     */
    public final static int VIEW_ONLY = 0x02;
}
